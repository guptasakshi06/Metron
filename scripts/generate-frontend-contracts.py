"""Generate checked TypeScript from the actual executable Pydantic contracts."""

import argparse
import json
from pathlib import Path
from typing import Any

from data_optimizer.intake.models import IntakeResult
from data_optimizer.observations.models import ObservationInput, PlanInput
from data_optimizer.optimization.assessment import AssessmentReport, AssessmentRequest
from data_optimizer.profiling.models import ProfileReport

ROOT = Path(__file__).resolve().parents[1]


def render(node: dict[str, Any], prefix: str) -> str:
    if "$ref" in node:
        return prefix + node["$ref"].split("/")[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    if "anyOf" in node:
        return " | ".join(render(v, prefix) for v in node["anyOf"])
    kind = node.get("type")
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(render(v, prefix) for v in node["prefixItems"]) + "]"
        return "Array<" + render(node.get("items", {}), prefix) + ">"
    if kind == "object":
        if "properties" in node:
            required = node.get("required", [])
            return (
                "{\n"
                + "\n".join(
                    f"  {json.dumps(k)}{'' if k in required else '?'}: {render(v, prefix)};"
                    for k, v in node["properties"].items()
                )
                + "\n}"
            )
        additional = node.get("additionalProperties", {})
        return (
            "Record<string, "
            + (
                render(additional, prefix)
                if isinstance(additional, dict)
                else "unknown"
            )
            + ">"
        )
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generated() -> str:
    parts = ["// Generated by scripts/generate-frontend-contracts.py. Do not edit.\n"]
    for model, prefix, mode in [
        (AssessmentRequest, "Input", "validation"),
        (AssessmentReport, "Result", "serialization"),
        (ProfileReport, "Local", "serialization"),
        (IntakeResult, "Assist", "serialization"),
        (PlanInput, "Adoption", "validation"),
        (ObservationInput, "Observed", "validation"),
    ]:
        schema = model.model_json_schema(mode=mode)
        for name, node in {**schema.get("$defs", {}), model.__name__: schema}.items():
            parts.append(f"export type {prefix}{name} = {render(node, prefix)}\n")
    return "\n".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        ROOT / "frontend/src/contracts.generated.ts": generated(),
        ROOT / "frontend/src/demo-request.json": (
            ROOT / "examples/s08-assessment-request.json"
        ).read_text(),
    }
    for path, value in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(
                    f"Stale frontend contract: {path.name}; regenerate contracts"
                )
        else:
            path.write_text(value)
